def append_script(slide, script: str) -> None:
    if not slide.has_notes_slide:
        return
    tf = slide.notes_slide.notes_text_frame
    if tf is None:
        return
    # 既存ノートの末尾に台本セクションを追加
    for line in ("\n", "─" * 40, "【台本 — 発表時に読む原稿】", ""):
        para = tf.add_paragraph()
        para.text = line
    for line in script.split("\n"):
        para = tf.add_paragraph()
        para.text = line


def main() -> None:
    prs = Presentation(PPTX_PATH)
    slides = list(prs.slides)
    print(f"総スライド数: {len(slides)}")
    for i, slide in enumerate(slides):
        idx = i + 1
        if idx not in SCRIPTS:
            print(f"  [SKIP] Slide {idx}")
            continue
        append_script(slide, SCRIPTS[idx])
        title = ""
        for shape in slide.shapes:
            if shape.has_text_frame and shape.text_frame.text.strip():
                title = shape.text_frame.text.strip().split("\n")[0][:45]
                break
        print(f"  [OK]   Slide {idx}: {title!r}")
    prs.save(PPTX_PATH)
    print(f"\n完了。保存先: {PPTX_PATH}")


if __name__ == "__main__":
    main()
