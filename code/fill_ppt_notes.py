def fill_note(slide, text: str):
    """空ノートにテキストを書き込む（既存ノートは触れない）"""
    if not slide.has_notes_slide:
        return
    tf = slide.notes_slide.notes_text_frame
    if tf is None:
        return
    existing = (tf.text or "").strip()
    if existing:
        return  # 既存ノートは触れない
    tf.clear()
    for i, line in enumerate(text.split("\n")):
        if i == 0:
            para = tf.paragraphs[0]
        else:
            para = tf.add_paragraph()
        para.text = line
        for run in para.runs:
            run.font.size = Pt(12)


def main():
    prs = Presentation(PPTX_PATH)
    filled = 0
    for idx, text in NOTES.items():
        if idx < len(prs.slides):
            slide = prs.slides[idx]
            title = ""
            try:
                title = slide.shapes[0].text_frame.text.strip()[:50]
            except:
                pass
            fill_note(slide, text)
            filled += 1
            print(f"  [Slide {idx+1:02d}] ノート記入: {title!r}")

    prs.save(PPTX_PATH)
    print(f"\n完了: {filled} スライドにノートを記入")
    print(f"保存先: {PPTX_PATH}")


if __name__ == "__main__":
    main()
