# ── ノート書き込み ──────────────────────────────────────────────────────────

def set_note(slide, text: str) -> None:
    if not slide.has_notes_slide:
        return
    tf = slide.notes_slide.notes_text_frame
    if tf is None:
        return
    tf.clear()
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if i == 0:
            para = tf.paragraphs[0]
        else:
            para = tf.add_paragraph()
        para.text = line


def main() -> None:
    prs = Presentation(PPTX_PATH)
    slides = list(prs.slides)
    print(f"総スライド数: {len(slides)}")

    for i, slide in enumerate(slides):
        idx = i + 1  # 1-based
        if idx not in NOTES:
            print(f"  [SKIP] Slide {idx}: ノート定義なし")
            continue
        set_note(slide, NOTES[idx])
        title = ""
        for shape in slide.shapes:
            if shape.has_text_frame and shape.text_frame.text.strip():
                title = shape.text_frame.text.strip().split("\n")[0][:50]
                break
        print(f"  [OK]   Slide {idx}: {title!r}")

    prs.save(PPTX_PATH)
    print(f"\n完了。保存先: {PPTX_PATH}")


if __name__ == "__main__":
    main()
