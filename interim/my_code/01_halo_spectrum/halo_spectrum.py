# ============================================================
# 1. 必要な道具(ライブラリ)を読み込む
# ============================================================
# Pythonは「何もしなくてもできること」がとても少ない言語です。
# 「グラフを描きたい」「JSONファイルを読みたい」といった機能は、
# 他の人が作った便利な道具箱(ライブラリ)を読み込んで(import)使います。

import json                      # JSON形式のファイルを読み書きする道具
import matplotlib.pyplot as plt  # グラフを描く道具（"plt"という短い名前で使う約束）

# 日本語（漢字・ひらがな）をグラフに表示するには、日本語対応フォントを
# 明示的に登録してあげる必要があります（登録しないと文字化け□になる）。
# これは"見た目のオシャレ"ではなく、文字化けを防ぐための技術的に必須の設定です。
from matplotlib import font_manager as _fm
_fm.fontManager.addfont("/home/arsei/.local/share/fonts/NotoSansCJKjp-Regular.otf")
plt.rcParams["font.family"] = "Noto Sans CJK JP"


# ============================================================
# 2. JSONファイルを読み込む
# ============================================================
# JSONファイルは中身がPythonの「辞書(dict)」と「リスト(list)」の組み合わせで
# できているテキストファイルです。json.load()を使うと、ファイルの中身を
# そのままPythonの辞書・リストとして読み込めます。
# 下のファイルは「cos(b)立体角補正を入れた計算(v2_cosb)」の結果です。
# このスクリプトはその数字を読んでグラフにするだけ(計算はしません)。

JSON_PATH = "results/mcmc_allbins_gasICS_v2_cosb/halo_spectrum.json"
# 🔧 ここを変えてみよう: パスを "results/mcmc_allbins_gasICS_v1/halo_spectrum.json"
#    (cos(b)補正を入れる前の古い版)に変えて実行すると、有意度がどう違うか
#    見比べられます。補正で全ビンの有意度が少し上がったことが分かるはずです。

with open(JSON_PATH) as f:
    # "with open(...) as f:" は「ファイルを開いて、使い終わったら自動で
    # 閉じてくれる」書き方です。f がファイルの中身を表す変数になります。
    data = json.load(f)  # data は辞書(dict)になる

# data["bins"] は「13個のビン(エネルギー区間)それぞれの結果」が
# 1個ずつ入った「リスト」です。リストは [要素0, 要素1, 要素2, ...] という
# 順番に並んだ箱のようなものです。
bins = data["bins"]
print(f"ビンの数: {len(bins)}")  # len() は「リストの長さ(要素数)」を調べる関数


# ============================================================
# 3. グラフに必要な数字だけを、リストに取り出す
# ============================================================
# 13個のビンそれぞれから「エネルギー」と「有意度」を1つずつ取り出して、
# 新しいリストに詰め替えます(リスト内包表記という書き方)。

energy_list = [b["e_center_gev"] for b in bins]
# 意味: bins の中の要素(1個ずつ b という名前で呼ぶ)それぞれについて、
#       b["e_center_gev"](そのビンのエネルギー[GeV])を取り出し、
#       新しいリストにする。for文を1行で書けるようにした書き方。
# 普通のfor文で書くと同じ意味になります:
#   energy_list = []
#   for b in bins:
#       energy_list.append(b["e_center_gev"])

sigma_list = [b["significance_sigma"] for b in bins]  # 有意度[シグマ]


# ============================================================
# 4. 図を用意する(有意度1枚だけ)
# ============================================================
# 以前は上下2段(上:f_halo、下:有意度)でしたが、発表では有意度だけ使うので
# 1枚に簡略化しました。plt.subplots() は「図の枠」を1つ作る関数です。
fig, ax = plt.subplots(
    figsize=(9, 5),   # 図の大きさ [インチ]。(横, 縦)の順
    # 🔧 ここを変えてみよう: (9,5) の数字を変えると図の縦横比が変わります
)

ax.set_xscale("log")  # 横軸(エネルギー)を対数目盛りにする
                       # (1.5 GeVから814 GeVまで桁が違いすぎるため)
# 🔧 ここを変えてみよう: "log" を "linear" にすると横軸が普通の等間隔目盛りに
#    なります(低エネルギー側の点が左端に押しつぶされて見づらくなるはず。
#    対数目盛りが必要な理由が体感できます)


# ------------------------------------------------------------
# 5. 有意度スペクトルを描く
# ------------------------------------------------------------
ax.plot(
    energy_list, sigma_list,
    "o-",            # 🔧 ここを変えてみよう: "o-"(丸+線)を "s--"(四角+点線)
                     #    や "^:"(三角+点線)に変えると見た目が変わります
)
ax.axhline(5, color="red", ls="--", alpha=0.5)   # +5σの目安線(検出の目安)
# 🔧 ここを変えてみよう: 上の "5" を別の数字(例えば2)に変えると目安線が動きます

# Totani (2025) が報告した21 GeVビンの有意度レンジ(13-19σ)を薄い帯で参考表示。
# 自分の結果がこの範囲とどれくらい違うかを一目で比べられるようにする。
ax.axhspan(13, 19, color="green", alpha=0.12, label="Totani報告(21GeV): 13-19σ")

ax.set_ylabel("有意度 [σ]")
ax.set_xlabel("Energy [GeV]")
ax.set_title("全13ビン: NFWハロー有意度スペクトル(cos(b)補正版)")
ax.legend()  # 凡例(帯が何を表すか)を表示


# ============================================================
# 6. ファイルに保存する
# ============================================================
fig.tight_layout()  # 余白を自動調整して詰めすぎ・空きすぎを防ぐ
fig.savefig(
    "interim/my_code/01_halo_spectrum/my_halo_spectrum.png",
    dpi=130,               # 解像度(数字が大きいほど高精細=ファイルも重くなる)
)
plt.close()  # メモリ節約のため、描き終わった図を閉じる

print("完成: interim/my_code/01_halo_spectrum/my_halo_spectrum.png")
