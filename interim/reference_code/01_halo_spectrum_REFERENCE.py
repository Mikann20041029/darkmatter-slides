"""
【答えコード】スライド7「全13ビンでのハロー有意度スペクトル」の作り方

★このファイルの使い方★
このコードは「もう計算が終わったあとの数字(JSONファイル)」を読み込んで、
グラフを描くだけのコードです。難しい計算(MCMCやGALPROPの読み込み)は
一切していません。「グラフを描く部分」だけを取り出したものです。

自分で書くときは、interim/my_code/01_halo_spectrum/ フォルダに
新しい.pyファイルを作って、このコードを見ながら、写経ではなく
「1行ずつ意味を理解してから」自分の言葉で書き直してください。
"""

# ============================================================
# 1. 必要な道具(ライブラリ)を読み込む
# ============================================================
# Pythonは「何もしなくてもできること」がとても少ない言語です。
# 「グラフを描きたい」「JSONファイルを読みたい」といった機能は、
# 他の人が作った便利な道具箱(ライブラリ)を読み込んで(import)使います。

import json                      # JSON形式のファイルを読み書きする道具
import matplotlib.pyplot as plt  # グラフを描く道具（"plt"という短い名前で使う約束）

# 日本語（漢字・ひらがな）をグラフに表示するには、日本語対応フォントを
# 明示的に登録してあげる必要があります（登録しないと文字化け□になる）。
from matplotlib import font_manager as _fm
_fm.fontManager.addfont("/home/arsei/.local/share/fonts/NotoSansCJKjp-Regular.otf")
plt.rcParams["font.family"] = "Noto Sans CJK JP"  # 以降、全部のグラフでこのフォントを使う設定


# ============================================================
# 2. JSONファイルを読み込む
# ============================================================
# JSONファイルは中身がPythonの「辞書(dict)」と「リスト(list)」の組み合わせで
# できているテキストファイルです。json.load()を使うと、ファイルの中身を
# そのままPythonの辞書・リストとして読み込めます。

JSON_PATH = "results/mcmc_allbins_gasICS_v1/halo_spectrum.json"

with open(JSON_PATH) as f:
    # "with open(...) as f:" は「ファイルを開いて、使い終わったら自動で
    # 閉じてくれる」書き方です。f がファイルの中身を表す変数になります。
    data = json.load(f)  # data は辞書(dict)になる

# data の中身がどうなっているか、実際に確認してみましょう
# （試しに以下の1行のコメントを外して実行すると、中身が全部表示されます）
# print(data.keys())

# data["bins"] は「13個のビン(エネルギー区間)それぞれの結果」が
# 1個ずつ入った「リスト」です。リストは [要素0, 要素1, 要素2, ...] という
# 順番に並んだ箱のようなものです。
bins = data["bins"]
print(f"ビンの数: {len(bins)}")  # len() は「リストの長さ(要素数)」を調べる関数


# ============================================================
# 3. グラフに必要な数字だけを、リストに取り出す
# ============================================================
# 13個のビンそれぞれから「エネルギー」「f_haloの値」「有意度」を
# 1つずつ取り出して、新しい4つのリストに詰め替えます。
# これを「リスト内包表記」というPythonの書き方でやります↓

energy_list = [b["e_center_gev"] for b in bins]
# 意味: bins の中の要素(1個ずつ b という名前で呼ぶ)それぞれについて、
#       b["e_center_gev"](そのビンのエネルギー[GeV])を取り出し、
#       新しいリストにする。for文を1行で書けるようにした書き方です。
# 普通のfor文で書くと同じ意味になります:
#   energy_list = []
#   for b in bins:
#       energy_list.append(b["e_center_gev"])

f_halo_list     = [b["params"]["f_halo"]["median"] for b in bins]  # ハローの強さ(中央値)
f_halo_lo_list  = [b["params"]["f_halo"]["lo16"]    for b in bins]  # 誤差の下側(16パーセンタイル)
f_halo_hi_list  = [b["params"]["f_halo"]["hi84"]    for b in bins]  # 誤差の上側(84パーセンタイル)
sigma_list      = [b["significance_sigma"]          for b in bins]  # 有意度[シグマ]


# ============================================================
# 4. 誤差棒(エラーバー)の長さを計算する
# ============================================================
# グラフの縦線(エラーバー)は「中央値から見て、下にどれだけ・上にどれだけ
# 離れているか」という「差」の長さで指定する必要があります(中央値そのもの
# ではないので注意)。

err_lower = [med - lo for med, lo in zip(f_halo_list, f_halo_lo_list)]
err_upper = [hi - med for med, hi in zip(f_halo_list, f_halo_hi_list)]
# zip(A, B) は「2つのリストAとBから、同じ順番の要素を1組ずつペアにする」機能。
# 例: zip([1,2,3], [10,20,30]) → (1,10), (2,20), (3,30) というペアの並び


# ============================================================
# 5. 図を2段構成(上:f_halo, 下:有意度)で用意する
# ============================================================
fig, axes = plt.subplots(
    2, 1,                 # 2行1列 = 縦に2つ並んだグラフ
    figsize=(9, 8),       # 図全体の大きさ [インチ]
    sharex=True,          # 上下のグラフでx軸(横軸)を共有する
)
# axes は [上のグラフ, 下のグラフ] という2要素のリストのようなもの
# 【2026-07-16 方針】背景色・文字色などの凝った配色はあえて付けていない
# (matplotlibの初期設定=白背景・デフォルト色のまま)。学部生が書く最初の
# 図としてはこのくらいシンプルな方が自然、という理由。

for ax in axes:
    ax.set_xscale("log")          # 横軸(エネルギー)を対数目盛りにする
                                    # (1.5 GeVから814 GeVまで桁が違いすぎるため)


# ------------------------------------------------------------
# 5-1. 上段: f_halo(ハローの強さ)+ 誤差棒
# ------------------------------------------------------------
axes[0].errorbar(
    energy_list,               # x軸: エネルギー
    f_halo_list,                # y軸: f_haloの中央値
    yerr=[err_lower, err_upper],  # 誤差棒の長さ [下側のリスト, 上側のリスト]
    fmt="o-",                   # 点は丸(o)、点同士を線(-)でつなぐ。色は指定せずデフォルト任せ
    capsize=3,                  # 誤差棒の先端に付ける横線の長さ
)
axes[0].axhline(0, color="gray", ls=":")  # y=0の位置に横の点線を引く(目印)
axes[0].set_ylabel("f_halo (振幅)")  # 縦軸のラベル
axes[0].set_title("全13ビン: NFWハロー振幅・有意度スペクトル")


# ------------------------------------------------------------
# 5-2. 下段: 有意度[シグマ]
# ------------------------------------------------------------
axes[1].plot(energy_list, sigma_list, "o-")
axes[1].axhline(0, color="gray", ls=":")
axes[1].axhline(2, color="red", ls="--", alpha=0.5)   # +2σの目安線
axes[1].axhline(-2, color="red", ls="--", alpha=0.5)  # -2σの目安線
axes[1].set_ylabel("有意度 [σ]")
axes[1].set_xlabel("Energy [GeV]")  # 一番下だけ横軸ラベルを付ける


# ============================================================
# 6. ファイルに保存する
# ============================================================
fig.tight_layout()  # グラフ同士の間隔を自動調整して詰めすぎ・空きすぎを防ぐ
fig.savefig(
    "interim/my_code/01_halo_spectrum/my_halo_spectrum.png",
    dpi=130,               # 解像度(数字が大きいほど高精細=ファイルも重くなる)
)
plt.close()  # メモリ節約のため、描き終わった図を閉じる(たくさん図を作るときに重要)

print("完成: interim/my_code/01_halo_spectrum/my_halo_spectrum.png")
