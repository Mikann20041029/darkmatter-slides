def size_runs(tf, size):
    for p in tf.paragraphs:
        for r in p.runs:
            r.font.size = Pt(size)


def slide(title, items, note, size=28, body_w=None, body_top=None):
    s = prs.slides.add_slide(L["Title and Content"])
    s.shapes.title.text = title
    size_runs(s.shapes.title.text_frame, 38)
    body = s.placeholders[1]
    if body_w:
        body.width = Inches(body_w)
    if body_top is not None:
        body.top = Inches(body_top)
    tf = body.text_frame
    for i, it in enumerate(items):
        lvl, t = (1, it[1]) if isinstance(it, tuple) else (0, it)
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = t; p.level = lvl
        for r in p.runs:
            r.font.size = Pt(size - 6 if lvl else size)
    s.notes_slide.notes_text_frame.text = note
    return s



def fig_slide(title, fig, caption, note, left=0.6, top=1.6, width=None, height=None):
    s = prs.slides.add_slide(L["Title Only"])
    s.shapes.title.text = title
    size_runs(s.shapes.title.text_frame, 38)
    kw = {}
    if width: kw["width"] = Inches(width)
    if height: kw["height"] = Inches(height)
    s.shapes.add_picture(fig, Inches(left), Inches(top), **kw)
    if caption:
        tb = s.shapes.add_textbox(Inches(0.6), Inches(6.35), Inches(12.1), Inches(0.9))
        tb.text_frame.word_wrap = True
        tb.text_frame.paragraphs[0].text = caption
        size_runs(tb.text_frame, 22)
    s.notes_slide.notes_text_frame.text = note
    return s


