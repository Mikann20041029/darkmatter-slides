# 表紙の右下 Reference の書式 (位置と幅) をそのまま使う
REF_TEMPLATE = next(sh for sh in prs.slides[0].shapes if sh.has_text_frame and sh.text_frame.text.startswith("Reference"))
REF_X, REF_Y, REF_W = REF_TEMPLATE.left, REF_TEMPLATE.top, REF_TEMPLATE.width


def add_ref(s, text, y=None):
    """右下に「Reference: ...」を入れる (表紙と同じ位置・幅・太字の見出し)"""
    el = copy.deepcopy(REF_TEMPLATE._element)
    s.shapes._spTree.append(el)
    sh = s.shapes[-1]
    sh.left, sh.top, sh.width = REF_X, (REF_Y if y is None else Inches(y)), REF_W
    p = sh.text_frame.paragraphs[0]
    runs = p.runs
    runs[1].text = " " + text
    for r in runs[2:]:
        r._r.getparent().remove(r._r)
    for r in p.runs:
        r.font.size = Pt(14)


def title(s, t):
    s.shapes.title.text = t
    for p in s.shapes.title.text_frame.paragraphs:
        for r in p.runs:
            r.font.size = Pt(34)


def slide(t, items, note, ref=None, size=24):
    s = prs.slides.add_slide(L["Title and Content"])
    title(s, t)
    body = s.placeholders[1]
    body.left, body.width = Inches(0.92), Inches(11.5)
    body.top = Inches(1.6)
    body.height = Inches(4.5 if ref else 5.4)
    tf = body.text_frame
    for i, it in enumerate(items):
        lvl, txt = (1, it[1]) if isinstance(it, tuple) else (0, it)
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = txt
        p.level = lvl
        for r in p.runs:
            r.font.size = Pt(size - 4 if lvl else size)
    if ref:
        add_ref(s, ref)
    s.notes_slide.notes_text_frame.text = note
    return s


def fig_slide(t, fig, caption, note, ref=None, left=1.5, top=1.35, height=4.6, width=None):
    s = prs.slides.add_slide(L["Title Only"])
    title(s, t)
    if width:
        s.shapes.add_picture(fig, Inches(left), Inches(top), width=Inches(width))
    else:
        s.shapes.add_picture(fig, Inches(left), Inches(top), height=Inches(height))
    tb = s.shapes.add_textbox(Inches(0.5), Inches(6.0), Inches(12.3), Inches(0.5))
    tb.text_frame.word_wrap = True
    tb.text_frame.text = caption
    for r in tb.text_frame.paragraphs[0].runs:
        r.font.size = Pt(20)
    if ref:
        add_ref(s, ref, y=6.6)
    s.notes_slide.notes_text_frame.text = note
    return s


